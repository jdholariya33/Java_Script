// Indices in array :

let marks = [97, 66, 85, 73, 80, 93];

console.log("Marks : ", marks);

console.log("Marks at the 1st index : ", marks[1]);
console.log("Marks at the 3rd index : ", marks[3]);

// Arrays are Muttable, we can change the data using index.

marks[1] = 70;  // we can change the data.
marks[6] = 86;  // We can add the data.

console.log("Marks : ", marks);
