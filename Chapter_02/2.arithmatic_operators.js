// Arithmatic Operators

let a = 10;
let b= 3;

// Basic Arithmatic Operators

console.log("a = " , a , ", b = " , b); // a =  10,  b =  3
console.log("a + b = " , a + b); // a + b =  13
console.log("a - b = " , a - b); // a - b =  7
console.log("a * b = " , a * b); // a * b =  30
console.log("a / b = " , a / b); // a / b =  3.3333333333333335

// Advanced Arithmatic Operators

console.log("a % b = " , a % b); // a % b =  1
console.log("a ** b = " , a ** b); // a ** b =  1000

// Unary Operators

a = a + 1; // a = 11
console.log("a = " , a); // a =  11

a++; // a = 12
console.log("a = " , a); // a =  12 

a--; // a = 11
console.log("a = " , a); // a =  11


// post and pre increment/decrement operators

let x = 5;

console.log("x = " , x); // x =  5

// post increment
console.log("x++ = " , x++); // x++ =  5
console.log("x = " , x); // x =  6

// pre increment
console.log("++x = " , ++x); // ++x =  7    

console.log("x = " , x); // x =  7

// post decrement
console.log("x-- = " , x--); // x-- =  7
console.log("x = " , x); // x =  6

// pre decrement
console.log("--x = " , --x); // --x =  5
console.log("x = " , x); // x =  5