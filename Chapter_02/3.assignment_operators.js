// Assignment operators 
    // Are used to assign values to variables.

let a = 10;
let b = 5;

// Basic Assignment Operator

console.log("a = " , a , ", b = " , b); // a =  10,  b =  5

a += 4  // a = a + 4
console.log("a = " , a); // a =  14

a -= 2  // a = a - 2
console.log("a = " , a); // a =  12

a *= 3  // a = a * 3
console.log("a = " , a); // a =  36

a /= 2  // a = a / 2
console.log("a = " , a); // a =  18

a %= 5  // a = a % 5
console.log("a = " , a); // a =  3

a **= 4  // a = a ** 4
console.log("a = " , a); // a =  81