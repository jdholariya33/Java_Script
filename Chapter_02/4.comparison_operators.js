// Comparison Operators

 let a = 10;
 let b = 5;

// Basic Comparison Operators

console.log("a = " , a , ", b = " , b); // a =  10,  b =  5
console.log("a == b = " , a == b); // a == b =  false
console.log("a != b = " , a != b); // a != b =  true

console.log("a > b = " , a > b); // a > b =  true
console.log("a < b = " , a < b); // a < b =  false
console.log("a >= b = " , a >= b); // a >= b =  true
console.log("a <= b = " , a <= b); // a <= b =  false

let x = 10;
let y = "10";
console.log("x = " , x , ", y = " , y);
console.log("x == y = " , x == y); // x == y =  true
console.log("x === y = " , x === y); // x === y =  false